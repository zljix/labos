import React, {act} from 'react';
import test from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {createRoot} from 'react-dom/client';
import {useOffline} from '../src/platform/offline';
import SystemPanel from '../src/platform/SystemPanel';

test('download progress, failure, retry and waiting update preserve the active offline package', async t => {
  const dom = new JSDOM('<div id="root"></div>', {url:'https://lab.example/labos/'});
  const keys = ['window','document','location','navigator','isSecureContext','caches','MessageChannel','IS_REACT_ACT_ENVIRONMENT'];
  const prior = keys.map(key => [key, Object.getOwnPropertyDescriptor(globalThis,key)] as const);
  const events = new dom.window.EventTarget(), registration = new dom.window.EventTarget() as any;
  const active = {scriptURL:'https://lab.example/labos/sw.js', postMessage(_message:any, ports:any[]) {ports[0].postMessage({ready:true, build:'ui-test',version:'0.15.2-beta.1',count:205,bytes:16000000});}};
  registration.active = active;
  registration.update = async () => {};
  (events as any).register = async () => registration;
  const values:any = {window:dom.window,document:dom.window.document,location:dom.window.location,navigator:{onLine:true,serviceWorker:events},isSecureContext:true,caches:{},MessageChannel:class {port1:any;port2:any;constructor(){this.port1={close(){}};this.port2={postMessage:(data:any)=>queueMicrotask(()=>this.port1.onmessage({data}))}}},IS_REACT_ACT_ENVIRONMENT:true};
  Object.assign(dom.window,{caches:{}});
  for (const [key,value] of Object.entries(values)) Object.defineProperty(globalThis,key,{value,configurable:true,writable:true});
  const root = createRoot(document.getElementById('root')!);
  t.after(async()=>{await act(async()=>root.unmount());dom.window.close();for(const [key,descriptor] of prior){if(descriptor)Object.defineProperty(globalThis,key,descriptor);else delete (globalThis as any)[key];}});
  function View(){const state=useOffline();return <SystemPanel offline={state} busy={false} saveStatus="Spremljeno lokalno" update={async()=>{}}/>;}
  await act(async()=>{root.render(<View/>);});
  const text=()=>document.body.textContent!;
  assert.match(text(),/Paket spreman za offline rad/);
  const installing = new dom.window.EventTarget() as any;
  installing.scriptURL=active.scriptURL; installing.state='installing'; registration.installing=installing;
  await act(async()=>registration.dispatchEvent(new dom.window.Event('updatefound')));
  const message=async(data:any, source:any=installing)=>act(async()=>events.dispatchEvent(new dom.window.MessageEvent('message',{data,source})));
  await message({type:'LAB_PACKAGE_PROGRESS',version:'0.15.3-beta.1',completed:8,total:205});
  assert.match(text(),/provjereno 8 od 205/);
  assert(document.querySelector<HTMLButtonElement>('.system-actions button')!.disabled);
  await message({type:'LAB_PACKAGE_ERROR',message:'ignored'}, {scriptURL:'https://other.example/sw.js'});
  assert(!text().includes('ignored'));
  await message({type:'LAB_PACKAGE_ERROR',message:'/labos/runtime/micropython.wasm: Sadržaj ne odgovara očekivanoj verziji.'});
  await act(async()=>{installing.state='redundant'; registration.installing=null; installing.dispatchEvent(new dom.window.Event('statechange'));});
  assert.match(document.querySelector('[role="alert"]')!.textContent!,/micropython.wasm/);
  assert.match(text(),/Paket spreman za offline rad/);
  assert(!document.querySelector<HTMLButtonElement>('.system-actions button')!.disabled);
  await act(async()=>document.querySelector<HTMLButtonElement>('.system-actions button')!.click());
  assert.match(document.querySelector('[role="alert"]')!.textContent!,/micropython.wasm/, 'inspection of the old package must not erase the new download failure');
  await act(async()=>{registration.installing=installing;installing.state='installing';registration.dispatchEvent(new dom.window.Event('updatefound'));});
  await message({type:'LAB_PACKAGE_PROGRESS',version:'0.15.3-beta.1',completed:205,total:205});
  assert.match(text(),/Spremanje paketa u preglednik/);
  assert.equal(document.querySelector('[role="alert"]'),null);
  await message({type:'LAB_PACKAGE_READY'});
  await act(async()=>{registration.waiting=installing;registration.installing=null;installing.state='installed';installing.dispatchEvent(new dom.window.Event('statechange'));});
  assert.match(text(),/Spremi i otvori novu verziju/);
  assert.match(text(),/paket 0.15.2-beta.1/);
});
